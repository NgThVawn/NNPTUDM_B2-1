function getCategoryClass(categoryName) {
    const categoryMap = {
        'Clothes': 'clothes',
        'Electronics': 'electronics',
        'Shoes': 'shoes',
        'Miscellaneous': 'miscellaneous'
    };
    return categoryMap[categoryName] || 'clothes';
}

function generateSlug(title) {
    return title
        .toLowerCase()
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .replace(/đ/g, 'd')
        .replace(/[^a-z0-9\s-]/g, '')
        .replace(/\s+/g, '-')
        .replace(/-+/g, '-')
        .trim();
}

function renderTable(dataToRender) {
    let body = document.getElementById("table-body");
    let emptyMessage = document.getElementById("empty-message");
    
    if (dataToRender.length === 0) {
        body.innerHTML = "";
        emptyMessage.style.display = "block";
        return;
    }
    
    emptyMessage.style.display = "none";
    
    // Calculate pagination
    const totalItems = dataToRender.length;
    const totalPages = itemsPerPage === 'all' ? 1 : Math.ceil(totalItems / itemsPerPage);
    
    if (currentPage > totalPages) {
        currentPage = totalPages || 1;
    }
    
    // Get items for current page
    const startIndex = itemsPerPage === 'all' ? 0 : (currentPage - 1) * itemsPerPage;
    const endIndex = itemsPerPage === 'all' ? totalItems : startIndex + itemsPerPage;
    const pageData = dataToRender.slice(startIndex, endIndex);
    
    body.innerHTML = "";
    
    pageData.forEach((product) => {
        const categoryClass = getCategoryClass(product.category);
        const description = product.description.length > 50 ? 
            product.description.substring(0, 50) + '...' : 
            product.description;
        
        body.innerHTML += 
        `<tr>
            <td style="text-align: center; font-weight: 600; color: #667eea;">${product.id}</td>
            <td><span class="product-title">${product.title}</span></td>
            <td><code style="background-color: #f8f9fa; padding: 4px 8px; border-radius: 4px; font-size: 0.85rem;">${product.slug}</code></td>
            <td><span class="price-cell">$${product.price.toLocaleString()}</span></td>
            <td><span class="description-cell">${description}</span></td>
            <td>
                <span class="category-badge ${categoryClass}">
                    ${product.category}
                </span>
            </td>
            <td style="text-align: center;">
                <img src='${product.image}' alt='${product.title}' class='product-image'/>
            </td>
            <td style="text-align: center;">
                <button class="btn btn-sm btn-info text-white me-1" onclick="viewProduct(${product.id})" title="Xem">
                    <i class="fas fa-eye"></i>
                </button>
                <button class="btn btn-sm btn-warning text-white me-1" onclick="editProduct(${product.id})" title="Sửa">
                    <i class="fas fa-edit"></i>
                </button>
                <button class="btn btn-sm btn-danger" onclick="deleteProduct(${product.id})" title="Xóa">
                    <i class="fas fa-trash"></i>
                </button>
            </td>
        </tr>`;
    });
    
    // Update pagination info
    updatePaginationInfo(startIndex + 1, endIndex, totalItems);
    renderPagination(totalPages);
}

function updatePaginationInfo(start, end, total) {
    document.getElementById('showing-info').textContent = `${start}-${end} của ${total} sản phẩm`;
}

function renderPagination(totalPages) {
    const pagination = document.getElementById('pagination');
    pagination.innerHTML = '';
    
    if (totalPages <= 1) return;
    
    // Previous button
    pagination.innerHTML += `
        <li class="page-item ${currentPage === 1 ? 'disabled' : ''}">
            <a class="page-link" href="#" onclick="changePage(${currentPage - 1}); return false;">
                <i class="fas fa-chevron-left"></i>
            </a>
        </li>
    `;
    
    // Page numbers
    let startPage = Math.max(1, currentPage - 2);
    let endPage = Math.min(totalPages, currentPage + 2);
    
    if (startPage > 1) {
        pagination.innerHTML += `
            <li class="page-item">
                <a class="page-link" href="#" onclick="changePage(1); return false;">1</a>
            </li>
        `;
        if (startPage > 2) {
            pagination.innerHTML += `<li class="page-item disabled"><span class="page-link">...</span></li>`;
        }
    }
    
    for (let i = startPage; i <= endPage; i++) {
        pagination.innerHTML += `
            <li class="page-item ${i === currentPage ? 'active' : ''}">
                <a class="page-link" href="#" onclick="changePage(${i}); return false;">${i}</a>
            </li>
        `;
    }
    
    if (endPage < totalPages) {
        if (endPage < totalPages - 1) {
            pagination.innerHTML += `<li class="page-item disabled"><span class="page-link">...</span></li>`;
        }
        pagination.innerHTML += `
            <li class="page-item">
                <a class="page-link" href="#" onclick="changePage(${totalPages}); return false;">${totalPages}</a>
            </li>
        `;
    }
    
    // Next button
    pagination.innerHTML += `
        <li class="page-item ${currentPage === totalPages ? 'disabled' : ''}">
            <a class="page-link" href="#" onclick="changePage(${currentPage + 1}); return false;">
                <i class="fas fa-chevron-right"></i>
            </a>
        </li>
    `;
}

function changePage(page) {
    currentPage = page;
    renderTable(filteredData);
}

